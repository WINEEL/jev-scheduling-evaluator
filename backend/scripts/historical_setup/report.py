@dataclass(slots=True)
class HistoricalComparison:
    historical_total: int
    historical_required: int
    historical_filled: int
    comparable: int
    exact_matches: int
    historical_invalid: int
    historical_invalid_unavailable: int
    historical_invalid_unqualified_lead: int
    historical_unmatched: int
    notes: list[str]


def compare_to_historical(
    adapted: AdaptedInput,
    result: SchedulingResult,
    dataset: HistoricalDataset,
) -> HistoricalComparison:
    """Structural comparison + a plain overlap statistic.

    An overlap match is the same (person, Sunday, role) appearing in both the
    solver's proposals and the historical roster. This is a *reference* number
    only -- the solver is never tuned to raise it.
    """
    si = adapted.scheduling_input
    name_to_membership: dict[str, int] = {}
    for vol in dataset.volunteers:
        name_to_membership.setdefault(vol.display_name.strip().lower(), vol.membership_id)

    candidates_by_id = {c.membership_id: c for c in si.candidates}

    solver_slots: set[tuple[int, datetime.date, str]] = set()
    for proposal in result.proposed_assignments:
        solver_slots.add(
            (
                proposal.membership_id,
                adapted.requirement_date[proposal.requirement_id],
                adapted.requirement_role_name[proposal.requirement_id],
            )
        )

    exact = 0
    comparable = 0
    invalid = 0
    invalid_unavail = 0
    invalid_unqual = 0
    unmatched = 0
    hist_filled = 0
    notes: list[str] = []

    for h in dataset.historical_assignments:
        hist_filled += 1
        mid = h.membership_id
        if mid is None:
            mid = name_to_membership.get(h.display_name.strip().lower())
        if mid is None:
            unmatched += 1
            continue
        comparable += 1
        if (mid, h.event_date, h.role_name) in solver_slots:
            exact += 1

        cand = candidates_by_id.get(mid)
        if cand is None:
            unmatched += 1
            continue
        event_id = adapted.event_id_by_date.get(h.event_date)
        role_id = adapted.role_id_by_name.get(h.role_name)
        bad = False
        if event_id is not None:
            state = cand.availability_for(event_id)
            if state is AvailabilityState.UNAVAILABLE:
                invalid_unavail += 1
                bad = True
        if role_id is not None and role_id == adapted.lead_role_id:
            if not cand.is_qualified_for(role_id):
                invalid_unqual += 1
                bad = True
        if event_id is not None and cand.is_blocked_on(h.event_date):
            bad = True
        if bad:
            invalid += 1

    return HistoricalComparison(
        historical_total=len(dataset.historical_assignments),
        historical_required=si.total_required_positions,
        historical_filled=hist_filled,
        comparable=comparable,
        exact_matches=exact,
        historical_invalid=invalid,
        historical_invalid_unavailable=invalid_unavail,
        historical_invalid_unqualified_lead=invalid_unqual,
        historical_unmatched=unmatched,
        notes=notes,
    )
